-- ==================== feedback ====================

CREATE TABLE IF NOT EXISTS feedback (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text,
  mobile text,
  email text,
  rating integer CHECK (rating IS NULL OR (rating >= 1 AND rating <= 5)),
  category text NOT NULL DEFAULT 'general',
  message text NOT NULL,
  order_number text,
  page text,
  status text NOT NULL DEFAULT 'new',
  created_at timestamptz DEFAULT now()
);

ALTER TABLE feedback ENABLE ROW LEVEL SECURITY;

-- Anyone — including guests — can leave feedback...
DROP POLICY IF EXISTS "insert_feedback" ON feedback;
CREATE POLICY "insert_feedback" ON feedback FOR INSERT
  TO anon, authenticated WITH CHECK (true);
-- ...but there is deliberately no SELECT policy, so submissions cannot be
-- listed or scraped from the browser. The dashboard reads them via the
-- service role.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'feedback_status_check') THEN
    ALTER TABLE feedback ADD CONSTRAINT feedback_status_check
      CHECK (status IN ('new', 'read', 'resolved'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'feedback_message_len') THEN
    ALTER TABLE feedback ADD CONSTRAINT feedback_message_len
      CHECK (char_length(message) BETWEEN 1 AND 4000);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_feedback_created ON feedback(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_feedback_status ON feedback(status);

-- Submitters (including anonymous ones) must not be able to file feedback
-- straight into a "resolved" state; every new row starts as 'new' and is
-- triaged from the dashboard.
CREATE OR REPLACE FUNCTION feedback_force_new() RETURNS trigger AS $$
BEGIN
  NEW.status := 'new';
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS feedback_force_new_trg ON feedback;
CREATE TRIGGER feedback_force_new_trg
  BEFORE INSERT ON feedback
  FOR EACH ROW EXECUTE FUNCTION feedback_force_new();

-- ==================== product_overrides ====================

-- The storefront catalogue is static frontend data. Admin edits (price, MRP,
-- per-size stock, visibility) are stored here and layered on top at runtime.
CREATE TABLE IF NOT EXISTS product_overrides (
  product_id text PRIMARY KEY,
  price integer CHECK (price IS NULL OR price >= 0),
  mrp integer CHECK (mrp IS NULL OR mrp >= 0),
  stock jsonb,
  is_active boolean NOT NULL DEFAULT true,
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE product_overrides ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "read_product_overrides" ON product_overrides;
CREATE POLICY "read_product_overrides" ON product_overrides FOR SELECT
  TO anon, authenticated USING (true);
-- No write policies: only the admin edge function (service role) may change them.
