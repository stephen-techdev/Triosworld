/*
# Payments (UPI), Admin Dashboard, Feedback & Product Overrides

Extends the existing schema so TriosWorld can take real UPI payments, issue
PDF receipts to guests, and run an admin dashboard. Nothing here removes or
renames existing structures.

## Design notes

### Server-authoritative orders
Orders are **created by the `trios-pay` edge function using the service role**,
never by the browser. That is why `orders` gets no INSERT policy: a client can
no longer write its own `total` (a real hole in the previous checkout, which
inserted straight from the browser). The function reprices every line from
`supabase/functions/_shared/prices.ts` before creating a payment.

### Guest checkout
`orders.user_id` becomes nullable so guests can order without an account.
`customer_name`, `customer_mobile` and `customer_email` are denormalised onto
the order so the record is complete on its own.

### Receipt access without an account
Each order carries `receipt_token` — a 32-char random hex string. Guest receipt
downloads are authorised by (order_number + receipt_token) inside the edge
function. The token is never exposed in lists; it is returned once at order
creation and kept by the customer's browser. Receipts are only served for
orders whose `payment_status = 'paid'`.

### Payment states (requirement: pending / failed / delayed)
`payment_status` ∈ pending | paid | failed | expired | refunded.
`expired` deliberately covers "the customer opened the QR but never completed
it" so abandoned baskets are not reported as failures.
`order_events` keeps an append-only trail of every gateway callback and state
transition, which is what makes the admin view and reconciliation possible.

## New / changed objects
- ALTER `orders` — guest support + payment + receipt columns, indexes
- `order_events` — append-only payment/order audit trail (admin only)
- `admins` — dashboard operators, bcrypt password hashes, no client access
- `feedback` — customer feedback; anon may INSERT, only service role may SELECT
- `product_overrides` — admin price/stock edits layered over the static catalog

## Security
- RLS enabled on every new table.
- `admins`: **no policies at all** → unreadable from the browser, including for
  authenticated users. Only the service role (edge functions) can touch it.
- `feedback`: INSERT-only for anon/authenticated; no SELECT policy, so submitted
  feedback cannot be enumerated from the client.
- `product_overrides`: public SELECT (prices are public anyway), service-role writes.
- `orders`: unchanged owner SELECT; no client INSERT/UPDATE/DELETE.
*/

-- ==================== orders: guest + payment + receipt ====================

-- Guests can order without an account.
ALTER TABLE orders ALTER COLUMN user_id DROP NOT NULL;

ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_name text;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_mobile text;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_email text;

-- Payment lifecycle. Kept separate from `status` (fulfilment: placed →
-- dispatched → delivered) so a failed payment never masquerades as an order.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_status text NOT NULL DEFAULT 'pending';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_provider text;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_id text;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_reference text;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS amount_paid integer;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS paid_at timestamptz;

-- Unguessable, per-order bearer token for guest receipt downloads.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS receipt_token text;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS updated_at timestamptz DEFAULT now();

-- Gateway identifiers (razorpay_order_id, qr_id, qr_image_url) kept together so
-- new gateway fields never require another column.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS gateway_meta jsonb NOT NULL DEFAULT '{}'::jsonb;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'orders_payment_status_check') THEN
    ALTER TABLE orders ADD CONSTRAINT orders_payment_status_check
      CHECK (payment_status IN ('pending', 'paid', 'failed', 'expired', 'refunded'));
  END IF;
END $$;

-- One token per order; generated by the server, with a random default as a
-- safety net if a row is ever inserted by hand.
UPDATE orders SET receipt_token = replace(gen_random_uuid()::text, '-', '') WHERE receipt_token IS NULL;
ALTER TABLE orders ALTER COLUMN receipt_token SET DEFAULT replace(gen_random_uuid()::text, '-', '');

CREATE UNIQUE INDEX IF NOT EXISTS idx_orders_receipt_token ON orders(receipt_token);
CREATE INDEX IF NOT EXISTS idx_orders_payment_status ON orders(payment_status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_payment_id ON orders(payment_id) WHERE payment_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_orders_customer_mobile ON orders(customer_mobile);

-- ==================== order_events (payment audit trail) ====================

CREATE TABLE IF NOT EXISTS order_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  event text NOT NULL,
  detail jsonb,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE order_events ENABLE ROW LEVEL SECURITY;

-- Customers may see the trail for their own orders; admins read everything via
-- the service role. Guests get nothing (their user_id is null).
DROP POLICY IF EXISTS "select_own_order_events" ON order_events;
CREATE POLICY "select_own_order_events" ON order_events FOR SELECT
  TO authenticated USING (
    EXISTS (SELECT 1 FROM orders o WHERE o.id = order_events.order_id AND o.user_id = auth.uid())
  );

CREATE INDEX IF NOT EXISTS idx_order_events_order ON order_events(order_id, created_at DESC);

-- ==================== admins ====================

